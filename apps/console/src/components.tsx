export function LangSwitch({ lang, onChange }: { lang: Lang; onChange: (l: Lang) => void }) {
  return (
    <div className="lang-switch" role="group">
      <button type="button" className={lang === "en" ? "on" : ""} onClick={() => onChange("en")}>
        English
      </button>
      <button type="button" className={lang === "zh" ? "on" : ""} onClick={() => onChange("zh")}>
        中文
      </button>
    </div>
  );
}

export function Pill({ status, label }: { status: string; label: string }) {
  return <span className={`pill ${status}`}>{label}</span>;
}

export function Modal({
  open,
  title,
  children,
  footer,
  onClose,
}: {
  open: boolean;
  title: string;
  children: ReactNode;
  footer: ReactNode;
  onClose: () => void;
}) {
  if (!open) return null;
  return (
    <div className="scrim" onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className="modal">
        <h3>{title}</h3>
        <div className="body">{children}</div>
        <div className="foot">{footer}</div>
      </div>
    </div>
  );
}

